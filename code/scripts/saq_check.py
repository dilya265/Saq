# Признаки обычных сообщений: вычитаем баллы
SAFE = [
    (r"(никому не сообщайте|никогда не просит|ешкімге.{0,20}айтпаңыз|ешқашан.{0,25}сұрамайды)", 5),
    (r"(оплата .{0,15}прошла|төлеміңіз сәтті|покупка .{0,15}(прошла|сәтті)|сәтті өтті)", 2),
]

RED, YELLOW = 4, 2


def check(text):
    t = text.lower()
    score, reasons = 0, []
    for name, w, pat, why in RULES:
        if re.search(pat, t):
            score += w
            reasons.append(why)
    for pat, w in SAFE:
        if re.search(pat, t):
            score -= w
    if score >= RED:
        color = "red"
    elif score >= YELLOW:
        color = "yellow"
    else:
        color = "green"
    return color, score, reasons


LABEL = {"red": "🔴 Похоже на мошенничество", "yellow": "🟡 Будьте осторожны", "green": "🟢 Признаков не найдено"}


def evaluate(only_real=False):
    con = sqlite3.connect("saq.db")
    q = "SELECT text, label, source FROM messages"
    if only_real:
        q += " WHERE source NOT LIKE 'synthetic%'"
    rows = con.execute(q).fetchall()
    if not rows:
        print("Нет данных для проверки.")
        return
    tp = fn = fp = tn = 0
    missed, false_alarms = [], []
    for text, label, _ in rows:
        color, _, _ = check(text)
        flagged = color in ("red", "yellow")
        if label == "scam":
            if flagged: tp += 1
            else: fn += 1; missed.append(text)
        else:
            if flagged: fp += 1; false_alarms.append(text)
            else: tn += 1
    scam, ok = tp + fn, fp + tn
    print(f"Сообщений: {len(rows)} (мошенничество: {scam}, обычные: {ok})")
    if scam: print(f"Поймано мошенничеств: {tp}/{scam} = {tp/scam:.0%}")
    if ok: print(f"Ложные тревоги на обычных: {fp}/{ok} = {fp/ok:.0%}")
    print(f"Общая точность: {(tp+tn)/len(rows):.0%}")
    if only_real is False:
        print("\nВНИМАНИЕ: в данных есть synthetic. Такая точность завышена, для защиты считайте на 'eval real'.")
    for title, items in (("Пропущено", missed), ("Ложные тревоги", false_alarms)):
        if items:
            print(f"\n{title}:")
            for s in items[:10]:
                print("  -", s[:90])


if __name__ == "__main__":
    args = sys.argv[1:]
    if not args:
        print(__doc__)
    elif args[0] == "eval":
        evaluate(only_real=len(args) > 1 and args[1] == "real")
    else:
        color, score, reasons = check(" ".join(args))
        print(LABEL[color], f"(баллы: {score})")
        for r in reasons:
            print("  •", r)
